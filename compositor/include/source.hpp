#pragma once

#include "types.hpp"
#include <memory>
#include <string>
#include <string_view>

namespace securestream {

// Provenance records where a source's data comes from.
// This is visible in the UI and auditable. It is the core of the security model:
// every source declares its origin, and the compositor refuses to render
// anything without a declared provenance.
enum class SourceOrigin {
    HostWebcam,       // physical webcam passed through from the host
    HostMicrophone,   // physical mic passed through from the host
    HostGameCapture,  // game/window capture fed from the host daemon
    HostAudio,        // system/application audio from the host
    VMLocal,          // a file or resource stored in the VM's user layer
    Network,          // an NDI/SRT/WebRTC feed from the network
    Generated,        // text, colour, image generated by the compositor itself
};

inline std::string_view origin_to_string(SourceOrigin o) {
    switch (o) {
        case SourceOrigin::HostWebcam:      return "Host Webcam";
        case SourceOrigin::HostMicrophone:  return "Host Microphone";
        case SourceOrigin::HostGameCapture: return "Host Game Capture";
        case SourceOrigin::HostAudio:        return "Host Audio";
        case SourceOrigin::VMLocal:          return "VM Local";
        case SourceOrigin::Network:          return "Network";
        case SourceOrigin::Generated:        return "Generated";
    }
    return "Unknown";
}

// Source is the base class for everything that can produce video or audio.
// A source must be explicitly added to a scene to be rendered. There is no
// implicit desktop capture, no window scanning. If it's not a declared Source
// on a Scene, it doesn't reach the encoder.
class Source {
public:
    Source(std::string name, SourceOrigin origin)
        : name_(std::move(name)), origin_(origin) {}
    virtual ~Source() = default;

    // Non-copyable, movable.
    Source(const Source&) = delete;
    Source& operator=(const Source&) = delete;
    Source(Source&&) = default;
    Source& operator=(Source&&) = default;

    // Produce the next video frame. Returns an invalid Frame if no new frame
    // is available (the compositor will hold the previous frame).
    virtual Frame get_video_frame() = 0;

    // Produce the next audio chunk. Returns an invalid AudioChunk if silent.
    virtual AudioChunk get_audio_chunk() = 0;

    // Whether this source produces video.
    virtual bool has_video() const = 0;

    // Whether this source produces audio.
    virtual bool has_audio() const = 0;

    std::string_view name() const { return name_; }
    SourceOrigin origin() const { return origin_; }

    // Whether this source is currently permitted to render.
    // The compositor checks this before calling get_video_frame.
    bool permitted() const { return permitted_; }
    void set_permitted(bool p) { permitted_ = p; }

private:
    std::string name_;
    SourceOrigin origin_;
    bool permitted_ = true;
};

} // namespace securestream
